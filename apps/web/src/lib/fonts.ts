import localFont from 'next/font/local';

/**
 * تعریف فونت وزیرمتن از فایل‌های محلی مخزن.
 *
 * چرا `next/font/local` و نه `next/font/google`:
 * نسخه‌ی گوگل در *زمان بیلد* فایل را از `fonts.gstatic.com` دانلود می‌کند. یعنی
 * بیلد به دسترسی به دامنه‌ی گوگل وابسته می‌شود — و برای کاربران و سرورهای
 * داخل ایران این یک مسئله‌ی واقعی دسترس‌پذیری است، نه صرفاً بهینه‌سازی. در
 * تلاش قبلی همین اتفاق افتاد و بیلد با پیام «Retrying 1/3» به فونت جایگزین
 * سقوط کرد. با فایل محلی، نه بیلد و نه زمان‌اجرا هیچ‌گاه به شبکه دست نمی‌زنند.
 *
 * چرا همچنان `next/font` (و نه `@font-face` دستی در CSS):
 * `next/font` فایل را با نام دارای هش (fingerprint) و هدر کش تغییرناپذیر از
 * دامنه‌ی خودمان سرو می‌کند، و مهم‌تر اینکه `size-adjust` را خودکار محاسبه
 * می‌کند تا هنگام جایگزینی فونت جایگزین با وزیرمتن، چیدمان نپرد (CLS).
 * نوشتن دستی `@font-face` هر دو مزیت را از دست می‌دهد.
 */

/**
 * نکته‌ی مهم درباره‌ی `declarations` و `unicode-range`:
 * عمداً `unicode-range` تعریف نشده است. اگر آن را به بازه‌ی عربی/فارسی محدود
 * کنیم، نویسه‌های لاتین (که در همین رابط هم وجود دارند — رایانامه، کد مجوز،
 * مسیر API داخل `.ltr-island`) به فونت جایگزین سیستم می‌افتند و ناهماهنگ
 * دیده می‌شوند. وزیرمتن خودش لاتین کاملی دارد، پس محدود کردنش ضرر است.
 */
export const vazirmatn = localFont({
  src: [
    {
      path: '../assets/fonts/vazirmatn/Vazirmatn-Regular.woff2',
      weight: '400',
      style: 'normal',
    },
    {
      path: '../assets/fonts/vazirmatn/Vazirmatn-Medium.woff2',
      weight: '500',
      style: 'normal',
    },
    {
      path: '../assets/fonts/vazirmatn/Vazirmatn-SemiBold.woff2',
      weight: '600',
      style: 'normal',
    },
    {
      path: '../assets/fonts/vazirmatn/Vazirmatn-Bold.woff2',
      weight: '700',
      style: 'normal',
    },
  ],

  // متغیر CSS که Tailwind از طریق `fontFamily.sans` به آن ارجاع می‌دهد.
  variable: '--font-vazirmatn',

  // متن بلافاصله با فونت جایگزین دیده می‌شود و سپس وزیرمتن جایش را می‌گیرد.
  // صفحه‌ی سفید تا لحظه‌ی آماده شدن فونت، بدترین حالت برای کاربر است.
  display: 'swap',

  /**
   * فونت جایگزین با اولویت Tahoma.
   *
   * چرا Tahoma اول: تنها فونتی است که روی ویندوز به‌طور پیش‌فرض نصب است و
   * اتصال حروف فارسی را درست رندر می‌کند. Arial در ویندوزهای قدیمی‌تر فارسی را
   * بریده‌بریده نشان می‌دهد. این فقط برای چند صد میلی‌ثانیه‌ی اول اهمیت دارد،
   * اما همان لحظه اولین برداشت کاربر است.
   */
  fallback: ['Tahoma', 'Segoe UI', 'Arial', 'sans-serif'],

  /**
   * `adjustFontFallback` را روشن نگه می‌داریم (پیش‌فرض) تا Next با محاسبه‌ی
   * متریک، ابعاد فونت جایگزین را به وزیرمتن نزدیک کند و جهش چیدمان کم شود.
   */
  preload: true,
});
